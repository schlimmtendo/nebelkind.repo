#!/usr/bin/env python3
"""Add keyboard ParentDir/Backspace support to the NebelFlix TV guide.

Patch only the target 0.2.3 ZIP generated by build_overrides.py.
Fail closed on unexpected sources. Does not change channels, EPG or playback.
"""
from pathlib import Path
from zipfile import ZipFile
import json
import os
import tempfile

ROOT = Path(__file__).resolve().parents[1]
AID = "plugin.video.nebelflix.tv"
SOURCE = AID + "/resources/lib/guide.py"
VERSION = json.loads((ROOT / "release_versions.json").read_text(encoding="utf-8"))["plugin.video.nebelflix.tv"]
MARK = "ACTION_PARENT_DIR=9"


def fix(text):
    if MARK in text and "if action.getId() in (ACTION_PARENT_DIR,ACTION_PREVIOUS_MENU,ACTION_NAV_BACK):" in text:
        return text
    nl = "\r\n" if "\r\n" in text else "\n"
    old_constant = "ACTION_PREVIOUS_MENU=10"
    old_handler = "if action.getId() in (ACTION_PREVIOUS_MENU,ACTION_NAV_BACK):"
    if text.count(old_constant) != 1 or text.count(old_handler) != 1:
        raise ValueError("Unexpected TV guide: refusing unsafe navigation patch")
    text = text.replace(old_constant, MARK + nl + old_constant, 1)
    text = text.replace(old_handler,
                        "if action.getId() in (ACTION_PARENT_DIR,ACTION_PREVIOUS_MENU,ACTION_NAV_BACK):", 1)
    compile(text, SOURCE, "exec")
    return text


def main():
    versions = json.loads((ROOT / "release_versions.json").read_text(encoding="utf-8"))
    if versions.get(AID) != VERSION:
        raise ValueError("Unexpected TV release plan, expected version " + VERSION)
    target = ROOT / "packages" / AID / (AID + "-" + VERSION + ".zip")
    if not target.is_file():
        raise ValueError("New TV package does not exist: " + str(target))
    with ZipFile(target) as original:
        names = original.namelist()
        if SOURCE not in names:
            bridge = original.read(AID + "/resources/lib/vavoo_bridge.py")
            if b"favorites_epg" not in bridge:
                raise ValueError("Neither legacy guide nor native Vavoo bridge found")
            print("Legacy TV guide retired; native Vavoo guide needs no patch")
            return
        previous = original.read(SOURCE)
        patched = fix(previous.decode("utf-8")).encode("utf-8")
        if patched == previous:
            print("TV guide remote Back already patched")
            return
        fd, tmp = tempfile.mkstemp(prefix="neb-tv-back-", suffix=".zip", dir=target.parent)
        os.close(fd)
        try:
            with ZipFile(tmp, "w") as result:
                for item in original.infolist():
                    result.writestr(item, patched if item.filename == SOURCE else original.read(item.filename))
            with ZipFile(tmp) as check:
                if check.testzip() is not None:
                    raise ValueError("Patched TV ZIP is corrupt")
                if MARK.encode() not in check.read(SOURCE):
                    raise ValueError("Patched navigation code missing")
            os.replace(tmp, target)
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)
    print("Updated Back/Backspace navigation in " + target.name)


if __name__ == "__main__":
    main()

